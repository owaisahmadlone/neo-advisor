"""The synthetic "truth plant": the real network the advisor never sees directly.

Its parameters are drawn away from the registry (the advisor's engineering view) so the
advisor is never tested on data generated by its own model (the "inverse crime"):

* wells are bottomhole IPR + lift models whose fitted wellhead curves differ from the
  registry's, with their own reservoir decline since the registry survey date;
* CGR falls with reservoir pressure and WGR creeps up, neither of which the advisor models;
* trunk and flowline liquid head is larger (a liquid-loading effect) and friction differs;
* ambient temperature, third-party rate, terminal headroom and nominations vary daily.

Every daily draw is keyed by (seed, gas day), so the plant has no hidden state: operating
the same gas day twice, or in any order, gives the same result.
"""

from __future__ import annotations

import math
from collections.abc import Callable, Iterable, Mapping, Sequence
from dataclasses import dataclass, fields, replace
from datetime import date, datetime
from itertools import pairwise

import numpy as np

from neo.domain.fixtures import DESIGN_MANIFOLD_BARA
from neo.domain.registry import Pipe, Registry, Well
from neo.physics.blend import Composition
from neo.physics.pipes import PipeHydraulics
from neo.physics.wells import BottomholeWell
from neo.synth.scenarios import Scenario, TimedEvent
from neo.synth.seeding import keyed_rng
from neo.verify.forward import Outcome, PhysicalNetwork, Setpoints, Violation, WellPhysics, simulate
from neo.verify.value import Valuation, value_outcome

NOMINAL_RATE_FRACTION = 0.85
INITIAL_SUCTION_BARA = 25.0
AMBIENT_RANGE_C = (28.0, 34.0)
THIRD_PARTY_SWING = 0.12
TERMINAL_HEADROOM_BBLD = 20_000.0
TERMINAL_SWING = 0.10
TRAIN_EVENTS = ("train_trip", "train_maintenance")
DELIVERABILITY_SLACK = 1e-3


@dataclass(frozen=True, slots=True)
class TrueWellModel:
    """``WellModel`` adapter over the truth-side bottomhole well."""

    well: BottomholeWell

    def rate(self, p_wh: float) -> float:
        return self.well.rate_at_wellhead(p_wh)

    def wellhead_pressure(self, q: float) -> float:
        """Exact inverse of ``rate``: the IPR and lift relation solved for p_wh at a given q."""
        w = self.well
        if q <= 0:
            return w.shut_in_wellhead_pressure
        lifted = w.p_res**2 - w.friction_f * q**2 - (q / w.c_r) ** (1 / w.n_r)
        return math.sqrt(lifted / math.exp(w.column_s)) if lifted > 0 else math.nan


@dataclass(frozen=True, slots=True)
class FailedWellModel:
    shut_in_bara: float

    def rate(self, p_wh: float) -> float:
        return 0.0

    def wellhead_pressure(self, q: float) -> float:
        return self.shut_in_bara if q <= 0 else math.nan


@dataclass(frozen=True, slots=True)
class TrueWell:
    """True well parameters; ``days`` count from the registry survey date."""

    well_id: str
    platform: str
    survey: BottomholeWell
    p_res_decline_bar_per_day: float
    cgr_survey: float
    cgr_exponent: float
    wgr_survey: float
    wgr_growth_per_day: float
    composition: Composition
    wellhead_temp_c: float
    choke_bore_in: float

    def bottomhole(self, days: int) -> BottomholeWell:
        return replace(self.survey, p_res=self.survey.p_res - self.p_res_decline_bar_per_day * days)

    def cgr(self, days: int) -> float:
        return self.cgr_survey * (self.bottomhole(days).p_res / self.survey.p_res) ** self.cgr_exponent

    def wgr(self, days: int) -> float:
        return self.wgr_survey * (1 + self.wgr_growth_per_day * days)

    def physics(self, days: int, *, failed: bool = False) -> WellPhysics:
        model = TrueWellModel(self.bottomhole(days))
        return WellPhysics(
            model=FailedWellModel(model.well.shut_in_wellhead_pressure) if failed else model,
            platform=self.platform,
            composition=self.composition,
            cgr=self.cgr(days),
            wgr=self.wgr(days),
            wellhead_temp_c=self.wellhead_temp_c,
            choke_bore_in=self.choke_bore_in,
        )


@dataclass(frozen=True, slots=True)
class DayConditions:
    gas_day: date
    ambient_c: float
    third_party_rates: Mapping[str, float]
    terminal_headroom_bbld: float
    nominations: Mapping[str, float]


@dataclass(frozen=True, slots=True)
class PeriodResult:
    """A steady stretch of the gas day between event boundaries."""

    start_utc: datetime
    end_utc: datetime
    physical: PhysicalNetwork
    setpoints: Setpoints
    outcome: Outcome

    @property
    def hours(self) -> float:
        return (self.end_utc - self.start_utc).total_seconds() / 3600

    @property
    def rates(self) -> dict[str, float]:
        return {w: o.rate for w, o in self.outcome.wells.items()}

    def contains(self, ts_utc: datetime) -> bool:
        return self.start_utc <= ts_utc < self.end_utc


@dataclass(frozen=True, slots=True)
class DayResult:
    gas_day: date
    requested: Setpoints
    conditions: DayConditions
    periods: tuple[PeriodResult, ...]
    daily: Outcome
    valuation: Valuation
    violations: tuple[Violation, ...]

    @property
    def well_rates(self) -> dict[str, float]:
        return {w: o.rate for w, o in self.daily.wells.items()}

    @property
    def end_rates(self) -> dict[str, float]:
        return self.periods[-1].rates

    def period_at(self, ts_utc: datetime) -> PeriodResult:
        return next(p for p in self.periods if p.contains(ts_utc))


class TruthPlant:
    """Simulates the real plant one gas day at a time and answers truth queries for the writer."""

    def __init__(self, registry: Registry, *, seed: int, scenario: Scenario, start: date) -> None:
        net = registry.network
        self.registry = registry
        self.seed = seed
        self.scenario = scenario
        self.start = start
        self.calendar = net.calendar
        self.survey_date = net.valid_from
        self.wells: dict[str, TrueWell] = {w.id: _draw_well(w, keyed_rng(seed, "well", w.id)) for w in net.wells}
        self.pipes: dict[str, PipeHydraulics] = {p.id: _draw_pipe(p, keyed_rng(seed, "pipe", p.id)) for p in net.pipes}
        self.holdups = {p.id: p.holdup for p in net.pipes if p.holdup is not None}
        self.events: tuple[TimedEvent, ...] = scenario.timed_events(self.calendar, start)

    def __repr__(self) -> str:
        return f"TruthPlant(seed={self.seed}, scenario={self.scenario.name!r}, start={self.start})"

    # ----------------------------------------------------------------- truth queries
    def days_since_survey(self, gas_day: date) -> int:
        return (gas_day - self.survey_date).days

    def conditions(self, gas_day: date) -> DayConditions:
        net, commercial = self.registry.network, self.registry.commercial
        rng = keyed_rng(self.seed, "day", gas_day)
        ambient = float(rng.uniform(*AMBIENT_RANGE_C))
        third_party = {
            s.id: s.nominal_rate_mmscfd * float(rng.uniform(1 - THIRD_PARTY_SWING, 1 + THIRD_PARTY_SWING))
            for s in net.third_party
        }
        headroom = TERMINAL_HEADROOM_BBLD * float(rng.uniform(1 - TERMINAL_SWING, 1 + TERMINAL_SWING))
        nominations = {
            c.id: c.dcq_mmbtu_d
            * float(
                np.clip(
                    rng.normal(self.scenario.nomination_mean, self.scenario.nomination_sd),
                    0,
                    c.mdq_mmbtu_d / c.dcq_mmbtu_d,
                )
            )
            for c in commercial.gsas
        }
        return DayConditions(gas_day, ambient, third_party, headroom, nominations)

    def active_events(self, at_utc: datetime) -> tuple[TimedEvent, ...]:
        return tuple(e for e in self.events if e.active_at(at_utc))

    def trains_available(self, at_utc: datetime) -> int:
        removed = sum(e.capacity_removed for e in self.active_events(at_utc) if e.type in TRAIN_EVENTS)
        return max(self.registry.network.compressor.trains - round(removed), 0)

    def failed_wells(self, at_utc: datetime) -> frozenset[str]:
        return frozenset(e.asset_id for e in self.active_events(at_utc) if e.type == "well_failure")

    def physical_network(self, at_utc: datetime) -> PhysicalNetwork:
        net = self.registry.network
        gas_day = self.calendar.gas_day_of(at_utc)
        days = self.days_since_survey(gas_day)
        cond = self.conditions(gas_day)
        active = self.active_events(at_utc)
        failed = self.failed_wells(at_utc)

        def removed(kind: str) -> float:
            return sum(e.capacity_removed for e in active if e.type == kind)

        return PhysicalNetwork(
            network=net,
            wells={w_id: w.physics(days, failed=w_id in failed) for w_id, w in self.wells.items()},
            pipes=self.pipes,
            holdups=self.holdups,
            train=net.compressor.train.map,
            fuel=net.compressor.fuel.model,
            ambient_c=cond.ambient_c,
            third_party={
                s.id: (cond.third_party_rates[s.id], s.composition, s.cgr_bbl_mmscf, s.wgr_bbl_mmscf)
                for s in net.third_party
            },
            plant_inlet_cap=max(net.plant.inlet_cap_mmscfd - removed("plant_derate"), 0.0),
            co2_removal_cap=max(net.plant.co2_removal_cap_mmscfd - removed("co2_removal_derate"), 0.0),
            condensate_headroom=cond.terminal_headroom_bbld,
        )

    def initial_setpoints(self) -> Setpoints:
        """Every available well at the fixture-style nominal rate, all trains, default routes."""
        net = self.registry.network
        failed = self.failed_wells(self.calendar.bounds_utc(self.start)[0])
        rates = {w.id: 0.0 if w.id in failed else _nominal_rate(w) for w in net.wells}
        return Setpoints(
            rates=rates,
            routes={p.id: p.export_options[0] for p in net.platforms},
            trains=net.compressor.trains,
            suction_bara=INITIAL_SUCTION_BARA,
        )

    # ----------------------------------------------------------------- operation
    def operate(
        self, gas_day: date, setpoints: Setpoints, *, previous_rates: Mapping[str, float] | None = None
    ) -> DayResult:
        """Apply ``setpoints`` for ``gas_day`` and return how the plant actually responded.

        ``previous_rates`` (the rates in force before the day) enables the slug-sweep check.
        """
        day_start, day_end = self.calendar.bounds_utc(gas_day)
        boundaries = {day_start, day_end} | {
            t for e in self.events for t in (e.start_utc, e.end_utc) if day_start < t < day_end
        }
        periods: list[PeriodResult] = []
        current = previous_rates
        for start, end in pairwise(sorted(boundaries)):
            applied = self._applied(setpoints, day_start, start)
            phys = self.physical_network(start)
            outcome = simulate(phys, applied, mode="respond", current_rates=current)
            periods.append(PeriodResult(start, end, phys, applied, outcome))
            current = periods[-1].rates
        conditions = self.conditions(gas_day)
        daily = _daily_outcome(setpoints, periods)
        well_ghv = {w_id: w.composition.ghv_btu_scf for w_id, w in self.wells.items()}
        valuation = value_outcome(self.registry, daily, conditions.nominations, well_ghv=well_ghv)
        return DayResult(gas_day, setpoints, conditions, tuple(periods), daily, valuation, _worst_violations(periods))

    def _applied(self, setpoints: Setpoints, day_start: datetime, at_utc: datetime) -> Setpoints:
        """What the plant can actually run: failed wells stay shut, tripped trains stop.

        A train lost during the day is not replaced by a standby until the next plan.
        """
        failed = self.failed_wells(at_utc)
        lost_today = sum(
            e.capacity_removed for e in self.active_events(at_utc) if e.type in TRAIN_EVENTS and e.start_utc > day_start
        )
        trains = max(min(setpoints.trains - round(lost_today), self.trains_available(at_utc)), 0)
        rates = {w: 0.0 if w in failed else q for w, q in setpoints.rates.items()}
        return replace(setpoints, rates=rates, trains=trains)


def _nominal_rate(well: Well) -> float:
    design = well.curve.rate(DESIGN_MANIFOLD_BARA[well.platform])
    return min(NOMINAL_RATE_FRACTION * design, well.rate_cap_mmscfd)


def _draw_well(well: Well, rng: np.random.Generator) -> TrueWell:
    """A bottomhole well whose deliverability at the design manifold pressure is near the registry's."""
    column_s = rng.uniform(0.12, 0.20)
    n_r = rng.uniform(0.70, 0.95)
    p_si = well.p_ws_bara * (1 + rng.normal(0, 0.01))
    p_res = p_si * math.exp(column_s / 2)
    p_ref = min(DESIGN_MANIFOLD_BARA[well.platform], 0.6 * p_si)
    q_ref = rng.normal(1.0, 0.07) * well.curve.rate(p_ref)
    lift_drawdown = p_res**2 - math.exp(column_s) * p_ref**2
    friction_share = rng.uniform(0.03, 0.10)
    bottomhole = BottomholeWell(
        c_r=q_ref / ((1 - friction_share) * lift_drawdown) ** n_r,
        n_r=n_r,
        p_res=p_res,
        column_s=column_s,
        friction_f=friction_share * lift_drawdown / q_ref**2,
    )
    co2 = float(np.clip(well.co2 + rng.uniform(-0.01, 0.01), 0.001, 0.99))
    ghv_hc = well.ghv_hc_btu_scf * (1 + rng.normal(0, 0.003))
    return TrueWell(
        well_id=well.id,
        platform=well.platform,
        survey=bottomhole,
        p_res_decline_bar_per_day=well.p_ws_decline_bar_per_day * rng.uniform(0.7, 1.3) * math.exp(column_s / 2),
        cgr_survey=well.cgr_bbl_mmscf * (1 + rng.normal(0, 0.05)),
        cgr_exponent=rng.uniform(1.3, 1.7),
        wgr_survey=well.wgr_bbl_mmscf * (1 + rng.normal(0, 0.05)),
        wgr_growth_per_day=rng.uniform(0.0003, 0.001),
        composition=Composition(
            co2=co2,
            h2s_ppmv=well.h2s_ppmv * (1 + rng.normal(0, 0.05)),
            hg_ug_sm3=well.hg_ug_sm3 * (1 + rng.normal(0, 0.05)),
            ghv_btu_scf=(1 - co2) * ghv_hc,
        ),
        wellhead_temp_c=well.wellhead_temp_c + rng.normal(0, 1.0),
        choke_bore_in=well.choke_bore_in,
    )


def _draw_pipe(pipe: Pipe, rng: np.random.Generator) -> PipeHydraulics:
    prior = pipe.hydraulics
    return PipeHydraulics(
        k_friction=prior.k_friction * rng.uniform(0.95, 1.05),
        liquid_head=prior.liquid_head * 1.3,
        holdup_beta=prior.holdup_beta * 0.85,
        elevation_s=prior.elevation_s,
    )


# --------------------------------------------------------------------- daily totals
def _weighted(values: Iterable[float], weights: Sequence[float]) -> float:
    return sum(w * v for w, v in zip(weights, values, strict=True))


def _weighted_map(maps: Sequence[Mapping[str, float]], weights: Sequence[float]) -> dict[str, float]:
    return {k: _weighted((m[k] for m in maps), weights) for k in maps[0]}


def _weighted_record[T](records: Sequence[T], weights: Sequence[float]) -> T:
    first = records[0]
    return type(first)(**{f.name: _weighted((getattr(r, f.name) for r in records), weights) for f in fields(first)})


def _daily_outcome(requested: Setpoints, periods: Sequence[PeriodResult]) -> Outcome:
    """Time-weighted daily totals; composition and sales quality weighted by volume."""
    total_hours = sum(p.hours for p in periods)
    weights = [p.hours / total_hours for p in periods]
    outcomes = [p.outcome for p in periods]

    def avg(get: Callable[[Outcome], float]) -> float:
        return _weighted((get(o) for o in outcomes), weights)

    inlet = avg(lambda o: o.plant_inlet)
    inlet_weights = [w * o.plant_inlet / inlet if inlet > 0 else w for w, o in zip(weights, outcomes, strict=True)]
    sales_volume = avg(lambda o: o.sales_volume)
    sales_weights = [
        w * o.sales_volume / sales_volume if sales_volume > 0 else w for w, o in zip(weights, outcomes, strict=True)
    ]
    sales_energy = avg(lambda o: o.sales_energy_total)
    return Outcome(
        setpoints=requested,
        wells={w: _weighted_record([o.wells[w] for o in outcomes], weights) for w in outcomes[0].wells},
        pressures=_weighted_map([o.pressures for o in outcomes], weights),
        arc_flow=_weighted_map([o.arc_flow for o in outcomes], weights),
        hub_inflow=avg(lambda o: o.hub_inflow),
        fuel=avg(lambda o: o.fuel),
        plant_inlet=inlet,
        inlet_composition=_weighted_record([o.inlet_composition for o in outcomes], inlet_weights),
        co2_removal_needed=avg(lambda o: o.co2_removal_needed),
        sales_volume=sales_volume,
        sales_energy_total=sales_energy,
        sales_ghv=sales_energy / sales_volume if sales_volume > 0 else 0.0,
        sales_co2=_weighted((o.sales_co2 for o in outcomes), sales_weights),
        our_energy=avg(lambda o: o.our_energy),
        condensate=avg(lambda o: o.condensate),
        our_condensate_by_well=_weighted_map([o.our_condensate_by_well for o in outcomes], weights),
        water=avg(lambda o: o.water),
        violations=tuple(v for o in outcomes for v in o.violations if not _is_solver_tolerance(v)),
    )


def _is_solver_tolerance(violation: Violation) -> bool:
    """Respond mode clips every well to its deliverability, so a hair over it is convergence slack."""
    return violation.limit == "well_deliverability" and violation.value - violation.bound <= DELIVERABILITY_SLACK * max(
        violation.bound, 1.0
    )


def _worst_violations(periods: Sequence[PeriodResult]) -> tuple[Violation, ...]:
    worst: dict[tuple[str, str], Violation] = {}
    real = (v for p in periods for v in p.outcome.hard_violations if not _is_solver_tolerance(v))
    for violation in real:
        key = (violation.limit, violation.subject)
        current = worst.get(key)
        if current is None or abs(violation.value - violation.bound) > abs(current.value - current.bound):
            worst[key] = violation
    return tuple(worst[k] for k in sorted(worst))


